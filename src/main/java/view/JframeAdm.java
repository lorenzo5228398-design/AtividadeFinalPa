    public void carregarTabela() {

        DefaultTableModel tabela = (DefaultTableModel) tbAdm.getModel();

        tabela.setRowCount(0);

        AdmDao dao = new AdmDao();

        List<Object[]> linhas = dao.listarReservasDetalhadas();

        for (Object[] linha : linhas) {
            tabela.addRow(linha);
        }

    }


